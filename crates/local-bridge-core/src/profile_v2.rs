//! ApplicationProfile V2: independent enterprise Web + local PersonalProfile overlay.
//!
//! Only shape, pre-run selection and capability intersection live here.
//! Neither a downloaded Profile nor a local registration grants execution rights.
//! The CloudFile ApplicationProfile V1 parser and behavior remain unchanged.
use crate::profile::{
    validate_profile_fresh, validate_profile_shape, ApplicationBrand, ApplicationProfile,
    ProfileChannel, ProfileUpdate,
};
use anyhow::{bail, Result};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use url::Url;

pub const PROFILE_V2_SCHEMA_VERSION: u32 = 2;

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApplicationProfileV2 {
    pub schema_version: u32,
    pub profile_id: String,
    pub provider: String,
    pub environment: String,
    pub revision: u64,
    pub expires_at: u64,
    pub application: ApplicationBrand,
    pub origin: String,
    #[serde(default)]
    pub services: BTreeMap<String, String>,
    #[serde(default)]
    pub channels: Vec<ProfileChannel>,
    #[serde(default)]
    pub update: Option<ProfileUpdate>,
    #[serde(default)]
    pub agent_policy: Option<AgentPolicy>,
    #[serde(default)]
    pub enterprise_ai_api: Option<EnterpriseAiApi>,
    #[serde(default)]
    pub mixed_context: MixedContext,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AgentPolicy {
    pub mode: AgentSelectionMode,
    #[serde(default)]
    pub preferred_providers: Vec<String>,
    #[serde(default)]
    pub allow_user_choice: bool,
}
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentSelectionMode {
    FirstReady,
    Disabled,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct EnterpriseAiApi {
    pub enabled: bool,
    pub protocol: String,
    pub api_path: String,
    pub grant_path: String,
    pub auth: String,
    pub stream: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MixedContext {
    #[serde(default)]
    pub mode: MixedMode,
    /// Requests ONLY. No personal provider or permission originates from the server.
    #[serde(default)]
    pub personal_capability_requests: Vec<String>,
    /// UI hints, not executable paths, mandatory installation or an allowlist.
    #[serde(default)]
    pub suggested_mcp_providers: Vec<String>,
}
impl Default for MixedContext {
    fn default() -> Self {
        Self {
            mode: MixedMode::Mixed,
            personal_capability_requests: Vec::new(),
            suggested_mcp_providers: Vec::new(),
        }
    }
}
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MixedMode {
    #[default]
    Mixed,
    EnterpriseOnly,
}

/// Generated by actual local Provider probes. Never trust a web/app-supplied
/// PersonalRuntime state or treat offline shape validation as authentication.
#[derive(Clone, Debug, Default)]
pub struct PersonalRuntime {
    pub agents: Vec<AgentReadiness>,
    pub mcp: Vec<McpReadiness>,
}
#[derive(Clone, Debug)]
pub struct AgentReadiness {
    pub id: String,
    pub installed: bool,
    pub authenticated: bool,
    pub api_ready: bool,
    pub task_compatible: bool,
    pub user_allowed: bool,
}
impl AgentReadiness {
    pub fn ready(&self) -> bool {
        self.installed
            && self.authenticated
            && self.api_ready
            && self.task_compatible
            && self.user_allowed
    }
}
#[derive(Clone, Debug)]
pub struct McpReadiness {
    pub id: String,
    pub registered: bool,
    pub api_ready: bool,
    pub user_allowed: bool,
}

fn valid_id(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 64
        && s.bytes()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'-' | b'_' | b'.'))
}

fn valid_path(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 256
        && s.starts_with('/')
        && !s.starts_with("//")
        && !s.contains("..")
        && s.bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'-' | b'_'))
}

impl ApplicationProfileV2 {
    /// Reuses the *unchanged* V1 common-field validation, without teaching
    /// the V1 deserializer to accept schema 2 or new enterprise fields.
    fn common_v1(&self) -> ApplicationProfile {
        ApplicationProfile {
            schema_version: 1,
            profile_id: self.profile_id.clone(),
            provider: self.provider.clone(),
            environment: self.environment.clone(),
            revision: self.revision,
            expires_at: self.expires_at,
            application: self.application.clone(),
            origin: self.origin.clone(),
            services: self.services.clone(),
            channels: self.channels.clone(),
            update: self.update.clone(),
        }
    }
}

pub fn validate_profile_v2_shape(v2: &ApplicationProfileV2) -> Result<()> {
    if v2.schema_version != PROFILE_V2_SCHEMA_VERSION {
        bail!("unsupported V2 profile schema");
    }
    validate_profile_shape(&v2.common_v1())?;

    if let Some(policy) = &v2.agent_policy {
        if policy.preferred_providers.len() > 8
            || policy.preferred_providers.iter().any(|p| !valid_id(p))
            || policy
                .preferred_providers
                .iter()
                .collect::<BTreeSet<_>>()
                .len()
                != policy.preferred_providers.len()
            || (policy.mode == AgentSelectionMode::FirstReady
                && policy.preferred_providers.is_empty())
        {
            bail!("invalid V2 agent policy");
        }
    }

    if v2.mixed_context.personal_capability_requests.len() > 16
        || v2.mixed_context.suggested_mcp_providers.len() > 16
        || v2
            .mixed_context
            .personal_capability_requests
            .iter()
            .chain(v2.mixed_context.suggested_mcp_providers.iter())
            .any(|x| !valid_id(x))
    {
        bail!("invalid V2 mixed capability declaration");
    }
    if v2.mixed_context.mode == MixedMode::EnterpriseOnly
        && !v2.mixed_context.personal_capability_requests.is_empty()
    {
        bail!("enterprise-only profile cannot request personal tools");
    }

    if let Some(ai) = &v2.enterprise_ai_api {
        if ai.protocol != "openai-chat-completions"
            || ai.auth != "scoped_ticket"
            || !ai.stream
            || !valid_path(&ai.api_path)
            || !valid_path(&ai.grant_path)
            || ai.api_path == ai.grant_path
            || (ai.enabled && !secure_ai_origin(&v2.origin))
        {
            bail!("invalid or unsafe V2 enterprise AI endpoint");
        }
    }
    Ok(())
}

fn secure_ai_origin(origin: &str) -> bool {
    let Ok(url) = Url::parse(origin) else {
        return false;
    };
    url.scheme() == "https"
        || (url.scheme() == "http"
            && matches!(url.host_str(), Some("localhost" | "127.0.0.1" | "[::1]")))
}

/// Freshness does not establish trusted origin, application user, local consent
/// or a right to run an Agent/MCP tool.
pub fn validate_profile_v2_fresh(v2: &ApplicationProfileV2, now: u64) -> Result<()> {
    validate_profile_v2_shape(v2)?;
    validate_profile_fresh(&v2.common_v1(), now)
}

/// Pick exactly one ready Provider *before* submission. A caller must not run
/// this again as automatic failover after a task has been accepted/started.
pub fn choose_agent<'a>(
    profile: &ApplicationProfileV2,
    personal: &'a PersonalRuntime,
    explicit_user_choice: Option<&str>,
) -> Option<&'a AgentReadiness> {
    let policy = profile.agent_policy.as_ref()?;
    if policy.mode == AgentSelectionMode::Disabled {
        return None;
    }
    if let Some(requested) = explicit_user_choice {
        if !policy.allow_user_choice || !policy.preferred_providers.iter().any(|id| id == requested)
        {
            return None;
        }
        return personal
            .agents
            .iter()
            .find(|x| x.id == requested && x.ready());
    }
    policy
        .preferred_providers
        .iter()
        .find_map(|id| personal.agents.iter().find(|x| x.id == *id && x.ready()))
}

/// Enterprise-originated personal tool requests must intersect *locally*
/// registered, verified and user-permitted providers. Hints are not grants.
pub fn available_personal_mcp<'a>(
    profile: &ApplicationProfileV2,
    personal: &'a PersonalRuntime,
) -> Vec<&'a str> {
    if profile.mixed_context.mode != MixedMode::Mixed
        || !profile
            .mixed_context
            .personal_capability_requests
            .iter()
            .any(|v| v == "mcp.tool.call")
    {
        return Vec::new();
    }
    personal
        .mcp
        .iter()
        .filter(|m| m.registered && m.api_ready && m.user_allowed)
        .map(|m| m.id.as_str())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn sample() -> ApplicationProfileV2 {
        serde_json::from_value(json!({
            "schema_version":2, "profile_id":"sample-ai-dev",
            "provider":"sample","environment":"dev","revision":1,"expires_at":5000,
            "application":{"id":"sample-ai","name":"Sample Web AI"},
            "origin":"https://app.example.test",
            "services":{"ai":"https://app.example.test/ai"},
            "channels":[{"id":"ai","title":"AI","kind":"web","entry":"/app",
                          "capabilities":["mcp.tool.call","ai.agent.run"]}],
            "agent_policy":{"mode":"first_ready","preferred_providers":["workbuddy","codex","pi"],
                            "allow_user_choice":true},
            "mixed_context":{"mode":"mixed","personal_capability_requests":["mcp.tool.call","communication.local"],
                             "suggested_mcp_providers":["wechat"]},
            "enterprise_ai_api":{"enabled":false,"protocol":"openai-chat-completions",
                                 "api_path":"/api/local-ai/v2","grant_path":"/api/local-ai/v2/grant",
                                 "auth":"scoped_ticket","stream":true}
        }))
        .unwrap()
    }

    fn agent(id: &str, ready: bool) -> AgentReadiness {
        AgentReadiness {
            id: id.into(),
            installed: true,
            authenticated: true,
            api_ready: ready,
            task_compatible: true,
            user_allowed: true,
        }
    }

    #[test]
    fn v1_is_not_affected_and_v2_rejects_unexpected_input() {
        let profile = sample();
        validate_profile_v2_shape(&profile).unwrap();
        validate_profile_v2_fresh(&profile, 4000).unwrap();
        assert!(serde_json::from_value::<ApplicationProfile>(
            serde_json::to_value(&profile).unwrap()
        )
        .is_err());
        let mut invalid = serde_json::to_value(&profile).unwrap();
        invalid["mixed_context"]["shell"] = "run";
        assert!(serde_json::from_value::<ApplicationProfileV2>(invalid).is_err());
    }

    #[test]
    fn v2_validation_rejects_external_paths_duplicates_and_unsafe_http_ai() {
        let mut p = sample();
        p.agent_policy.as_mut().unwrap().preferred_providers = vec!["pi".into(), "pi".into()];
        assert!(validate_profile_v2_shape(&p).is_err());
        p = sample();
        p.enterprise_ai_api.as_mut().unwrap().api_path = "//evil/ai".into();
        assert!(validate_profile_v2_shape(&p).is_err());
        p = sample();
        p.enterprise_ai_api.as_mut().unwrap().enabled = true;
        validate_profile_v2_shape(&p).unwrap();
        p.origin = "http://intranet.example.test".into();
        assert!(validate_profile_v2_shape(&p).is_err());
        p = sample();
        p.mixed_context.mode = MixedMode::EnterpriseOnly;
        assert!(validate_profile_v2_shape(&p).is_err());
    }

    #[test]
    fn order_checks_workbuddy_then_codex_then_pi_and_respects_manual_choice() {
        let p = sample();
        let state = PersonalRuntime {
            agents: vec![
                agent("pi", true),
                agent("workbuddy", false),
                agent("codex", true),
            ],
            mcp: Vec::new(),
        };
        assert_eq!(choose_agent(&p, &state, None).unwrap().id, "codex");
        assert_eq!(choose_agent(&p, &state, Some("pi")).unwrap().id, "pi");
        assert!(choose_agent(&p, &state, Some("workbuddy")).is_none());
        let state = PersonalRuntime {
            agents: vec![
                agent("pi", true),
                agent("workbuddy", true),
                agent("codex", true),
            ],
            mcp: Vec::new(),
        };
        assert_eq!(choose_agent(&p, &state, None).unwrap().id, "workbuddy");
        assert!(choose_agent(&p, &state, Some("not-configured")).is_none());
    }

    #[test]
    fn personal_wechat_is_optional_and_never_authorized_by_profile_alone() {
        let p = sample();
        let mut local = PersonalRuntime {
            agents: Vec::new(),
            mcp: vec![McpReadiness {
                id: "wechat".into(),
                registered: true,
                api_ready: true,
                user_allowed: false,
            }],
        };
        assert!(available_personal_mcp(&p, &local).is_empty());
        local.mcp[0].user_allowed = true;
        assert_eq!(available_personal_mcp(&p, &local), vec!["wechat"]);
        local.mcp[0].api_ready = false;
        assert!(available_personal_mcp(&p, &local).is_empty());
        // The Profile's "suggested" entry neither installs nor authorizes it.
        local.mcp.clear();
        assert!(available_personal_mcp(&p, &local).is_empty());
    }
}
